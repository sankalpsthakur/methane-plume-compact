#!/usr/bin/env python3
"""Build a single-file Kaggle kernel script: embeds src/starcop_edge (zlib+base64), injects CFG, appends main.py.
Usage: make_kernel.py <kernel_dir> [--cfg '{"json": ...}']      (kernel_dir contains main.py + kernel-metadata.json; writes script.py)"""
import argparse, base64, json, pathlib, sys, zlib

ap = argparse.ArgumentParser(); ap.add_argument("kdir"); ap.add_argument("--cfg", default="{}")
a = ap.parse_args()
root = pathlib.Path(__file__).resolve().parent.parent
kdir = pathlib.Path(a.kdir).resolve()
pkg = {p.name: p.read_text() for p in sorted((root / "src" / "starcop_edge").glob("*.py"))}
blob = base64.b64encode(zlib.compress(json.dumps(pkg).encode(), 9)).decode()
header = f'''# AUTO-GENERATED by scripts/make_kernel.py (do not edit); sources: src/starcop_edge/*.py + {kdir.name}/main.py
import base64, json, os, sys, zlib
_PKG = json.loads(zlib.decompress(base64.b64decode("{blob}")).decode())
os.makedirs("/tmp/pkg/starcop_edge", exist_ok=True)
for _n, _s in _PKG.items():
    open("/tmp/pkg/starcop_edge/" + _n, "w").write(_s)
sys.path.insert(0, "/tmp/pkg")
CFG = json.loads({a.cfg!r})
# ---------------------------------------------------------------- main.py
'''
(kdir / "script.py").write_text(header + (kdir / "main.py").read_text())
print("wrote", kdir / "script.py", (kdir / "script.py").stat().st_size, "bytes")
